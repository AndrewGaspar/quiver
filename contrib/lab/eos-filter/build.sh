#!/usr/bin/env bash
# Build the lab's EOS filter, a secur32.dll for each architecture (design/LAB.md section 3.1):
#
#   contrib/lab/eos-filter/build.sh <out-dir>     ->  <out-dir>/{x86_64,i686}/secur32.dll
#
# Needs x86_64-w64-mingw32-gcc and i686-w64-mingw32-gcc (mingw-w64-gcc on Arch). The export
# trampolines and the .def are generated from exports.list into <out-dir>/<arch>/gen/.
# tools/install-user.sh and the PKGBUILD run it into $CARGO_TARGET_DIR/eos-filter, and
# packaging/layout.sh installs the DLLs as $LIBDIR/lab/eos-filter/<arch>/secur32.dll.
set -euo pipefail
here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
out=${1:?usage: build.sh <out-dir>}

# The exports shim.c wraps, with their stdcall argument bytes (the i686 decoration).
declare -A wrapped=(
    [EncryptMessage]=16 [SealMessage]=16 [DeleteSecurityContext]=4
    [InitializeSecurityContextA]=48 [InitializeSecurityContextW]=48
    [InitSecurityInterfaceA]=0 [InitSecurityInterfaceW]=0
)
names=() present=()
while read -r n; do
    [[ -z $n || $n == \#* ]] && continue
    if [[ -n ${wrapped[$n]+x} ]]; then present+=("$n"); else names+=("$n"); fi
done <"$here/exports.list"
((${#present[@]} == ${#wrapped[@]})) || { echo "build.sh: exports.list lacks a wrapped export" >&2; exit 1; }

for arch in x86_64 i686; do
    cc=$arch-w64-mingw32-gcc
    command -v "$cc" >/dev/null || { echo "build.sh: $cc not found (install mingw-w64-gcc)" >&2; exit 1; }
    gen=$out/$arch/gen
    mkdir -p "$gen"
    {
        echo "// Generated by contrib/lab/eos-filter/build.sh from exports.list. Do not edit."
        for n in "${names[@]}"; do echo "void *p_$n;"; done
        echo "const char *const EF_PASS_NAMES[] = {"
        for n in "${names[@]}"; do echo "    \"$n\","; done
        echo "};"
        echo "void **const EF_PASS_PTRS[] = {"
        for n in "${names[@]}"; do echo "    &p_$n,"; done
        echo "};"
        echo "const int EF_PASS_COUNT = ${#names[@]};"
        for n in "${names[@]}"; do
            if [[ $arch == x86_64 ]]; then
                echo "__asm__(\".text\\n.p2align 4\\n.globl t_$n\\nt_$n: jmp *p_$n(%rip)\\n\");"
            else
                echo "__asm__(\".text\\n.p2align 4\\n.globl _t_$n\\n_t_$n: jmp *_p_$n\\n\");"
            fi
        done
    } >"$gen/exports.c"
    {
        echo "LIBRARY secur32.dll"
        echo "EXPORTS"
        for n in "${names[@]}"; do echo "  $n = t_$n"; done
        for n in "${present[@]}"; do
            if [[ $arch == x86_64 ]]; then echo "  $n = w_$n"; else echo "  $n = w_$n@${wrapped[$n]}"; fi
        done
    } >"$gen/secur32.def"
    "$cc" -std=gnu11 -O2 -Wall -Wextra -Werror -Wno-cast-function-type -shared -s \
        -o "$out/$arch/secur32.dll" "$here/shim.c" "$here/filter.c" "$gen/exports.c" "$gen/secur32.def" \
        -static-libgcc -Wl,--no-insert-timestamp
    echo "built $out/$arch/secur32.dll"
done
