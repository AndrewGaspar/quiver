//! Builds the virtual clock twice:
//!
//! - for the host (`cc`), linked into this crate so its tests (and `timing`) run the exact C
//!   the game runs;
//! - as the hook DLL, once per proxy name (`win/exports/<name>.txt`) and architecture, with
//!   `x86_64-w64-mingw32-gcc` and `i686-w64-mingw32-gcc`. Each export of the proxied DLL becomes
//!   a `jmp` through a table the DLL fills from the real one at load. The DLLs are embedded
//!   (`DLLS`); a missing cross compiler leaves that architecture out with a warning, and the
//!   lab then refuses the virtual clock for it with the reason.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::Command;

const PROXIES: &[&str] = &["version", "winmm", "dinput8", "dsound"];
/// (arch as the lab names it, compiler, extra flags)
const ARCHES: &[(&str, &str, &[&str])] = &[("x64", "x86_64-w64-mingw32-gcc", &[]), ("x86", "i686-w64-mingw32-gcc", &["-march=pentium4", "-mfpmath=sse"])];

fn exports(path: &Path) -> Vec<(u16, Option<String>)> {
    let text = std::fs::read_to_string(path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    text.lines()
        .filter(|l| !l.trim().is_empty() && !l.starts_with('#'))
        .map(|l| {
            let mut w = l.split_whitespace();
            let ord: u16 = w.next().unwrap().parse().unwrap();
            let name = w.next().filter(|n| *n != "-").map(str::to_owned);
            (ord, name)
        })
        .collect()
}

fn stubs(proxy: &str, arch: &str, ex: &[(u16, Option<String>)]) -> (String, String) {
    let mut c = format!("/* Generated by build.rs: the {proxy}.dll proxy's exports ({arch}). */\n#include <stddef.h>\n");
    let _ = writeln!(c, "const char ss_proxy[] = \"{proxy}\";\nconst int ss_count = {};", ex.len());
    let names: Vec<String> = ex.iter().map(|(_, n)| n.as_ref().map_or("NULL".to_owned(), |n| format!("\"{n}\""))).collect();
    let _ = writeln!(c, "const char *const ss_names[] = {{ {} }};", names.join(", "));
    let ords: Vec<String> = ex.iter().map(|(o, _)| o.to_string()).collect();
    let _ = writeln!(c, "const unsigned short ss_ords[] = {{ {} }};", ords.join(", "));
    let _ = writeln!(c, "__attribute__((used)) void *ss_real[{}];", ex.len());
    let ptr = if arch == "x64" { 8 } else { 4 };
    let us = if arch == "x64" { "" } else { "_" };
    c.push_str("__asm__(\".text\\n\"\n");
    for i in 0..ex.len() {
        let target = if arch == "x64" { format!("ss_real+{}(%rip)", i * ptr) } else { format!("_ss_real+{}", i * ptr) };
        let _ = writeln!(c, "  \".globl {us}ss_stub_{i}\\n{us}ss_stub_{i}: jmp *{target}\\n\"");
    }
    c.push_str("  );\n");
    let mut def = format!("LIBRARY {proxy}.dll\nEXPORTS\n");
    for (i, (ord, name)) in ex.iter().enumerate() {
        let _ = match name {
            Some(n) => writeln!(def, "  {n}=ss_stub_{i} @{ord}"),
            None => writeln!(def, "  ss_stub_{i} @{ord} NONAME"),
        };
    }
    (c, def)
}

fn main() {
    let here = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    let win = here.join("win");
    for f in ["vclock.c", "vclock.h", "hook.c"] {
        println!("cargo:rerun-if-changed=win/{f}");
    }
    for p in PROXIES {
        println!("cargo:rerun-if-changed=win/exports/{p}.txt");
    }

    cc::Build::new().file(win.join("vclock.c")).include(&win).flag_if_supported("-std=c11").warnings(true).compile("quiver_vclock");

    let mut rs = String::from("// Generated by build.rs: (arch, proxy, DLL bytes).\npub static DLLS: &[(&str, &str, &[u8])] = &[\n");
    let mut missing = Vec::new();
    for (arch, gcc, flags) in ARCHES {
        if Command::new(gcc).arg("--version").output().map(|o| !o.status.success()).unwrap_or(true) {
            println!("cargo:warning=no {gcc}: the quiver lab virtual clock won't be available for {arch} games");
            missing.push(*arch);
            continue;
        }
        for proxy in PROXIES {
            let ex = exports(&win.join("exports").join(format!("{proxy}.txt")));
            let (c, def) = stubs(proxy, arch, &ex);
            let dir = out.join(format!("{proxy}-{arch}"));
            std::fs::create_dir_all(&dir).unwrap();
            std::fs::write(dir.join("stubs.c"), c).unwrap();
            std::fs::write(dir.join("proxy.def"), def).unwrap();
            let dll = dir.join(format!("{proxy}.dll"));
            let st = Command::new(gcc)
                .args(["-O2", "-Wall", "-Wextra", "-Wno-unused-parameter", "-Wno-cast-function-type", "-std=gnu11", "-shared", "-s"])
                .args(*flags)
                .arg("-I")
                .arg(&win)
                .arg("-o")
                .arg(&dll)
                .arg(win.join("hook.c"))
                .arg(win.join("vclock.c"))
                .arg(dir.join("stubs.c"))
                .arg(dir.join("proxy.def"))
                .args(["-static-libgcc", "-Wl,--enable-stdcall-fixup", "-lpsapi"])
                .status()
                .unwrap_or_else(|e| panic!("{gcc}: {e}"));
            assert!(st.success(), "{gcc} failed building {proxy}.dll ({arch})");
            let _ = writeln!(rs, "    ({arch:?}, {proxy:?}, include_bytes!({:?})),", dll.display().to_string());
        }
    }
    rs.push_str("];\n");
    let _ = writeln!(rs, "/// Architectures the DLL couldn't be built for (no cross compiler).\npub static MISSING: &[&str] = &{missing:?};");
    std::fs::write(out.join("dlls.rs"), rs).unwrap();
}
