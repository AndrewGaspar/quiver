//! Builds `quiver-pad-probe.exe` (win/probe.c) with mingw for x64 and x86 and embeds it
//! (`PROBES`). A missing cross compiler leaves that architecture out with a warning;
//! `quiver lab pad status` then says the probe isn't built in.

use std::fmt::Write as _;
use std::path::PathBuf;
use std::process::Command;

const ARCHES: &[(&str, &str)] = &[("x64", "x86_64-w64-mingw32-gcc"), ("x86", "i686-w64-mingw32-gcc")];

fn main() {
    let here = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    println!("cargo:rerun-if-changed=win/probe.c");
    println!("cargo:rerun-if-changed=../../contrib/lab/72-quiver-lab-pad.rules");
    let mut rs = String::from("// Generated by build.rs: (arch, probe exe bytes).\npub static PROBES: &[(&str, &[u8])] = &[\n");
    for (arch, gcc) in ARCHES {
        if Command::new(gcc).arg("--version").output().map(|o| !o.status.success()).unwrap_or(true) {
            println!("cargo:warning=no {gcc}: quiver lab pad status can't probe {arch} prefixes");
            continue;
        }
        let exe = out.join(format!("quiver-pad-probe-{arch}.exe"));
        let st = Command::new(gcc)
            .args(["-O2", "-Wall", "-Wextra", "-std=gnu11", "-mwindows", "-s", "-o"])
            .arg(&exe)
            .arg(here.join("win/probe.c"))
            .args(["-ldinput8", "-ldxguid", "-lsetupapi", "-lhid", "-luuid", "-static-libgcc"])
            .status()
            .unwrap_or_else(|e| panic!("{gcc}: {e}"));
        assert!(st.success(), "{gcc} failed building the pad probe ({arch})");
        let _ = writeln!(rs, "    ({arch:?}, include_bytes!({:?})),", exe.display().to_string());
    }
    rs.push_str("];\n");
    std::fs::write(out.join("probes.rs"), rs).unwrap();
}
