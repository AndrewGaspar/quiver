#!/usr/bin/env python3
"""Generate the pass-through part of the 32-bit secur32.dll tap.

    gen.py <real-secur32.dll> <out-dir>

Writes exports.c (naked jmp trampolines to the real DLL) and secur32.def. The wrapped
functions (EncryptMessage, DecryptMessage, SealMessage, UnsealMessage, InitSecurityInterface*)
live in tap.c.
"""
import re, subprocess, sys
real, out = sys.argv[1], sys.argv[2]
dump = subprocess.run(["winedump", "-j", "export", real], capture_output=True, text=True).stdout
names = [m.group(1) for m in re.finditer(r"^\s+[0-9A-F]+\s+\d+\s+(\S+)", dump, re.M)]
wrapped = {"EncryptMessage": 16, "DecryptMessage": 16, "SealMessage": 16, "UnsealMessage": 16,
           "InitSecurityInterfaceA": 0, "InitSecurityInterfaceW": 0}
plain = [n for n in names if n not in wrapped]
c = ["// Generated by gen.py. Do not edit.", "#include <windows.h>",
     f"const char *TAP_NAMES[] = {{ {', '.join(repr(n).replace(chr(39), chr(34)) for n in plain)} }};",
     f"const int TAP_COUNT = {len(plain)};", f"void *TAP_REAL[{len(plain)}];"]
for i, n in enumerate(plain):
    c.append(f'__asm__(".globl _t_{n}\\n_t_{n}: jmp *_TAP_REAL+{4*i}\\n");')
open(f"{out}/exports.c", "w").write("\n".join(c) + "\n")
d = ["LIBRARY secur32", "EXPORTS"] + [f"  {n} = t_{n}" for n in plain]
d += [f"  {n} = w_{n}@{a}" for n, a in wrapped.items() if n in names]
open(f"{out}/secur32.def", "w").write("\n".join(d) + "\n")
print(f"{len(plain)} pass-through exports, {len(wrapped)} wrapped")
