#!/usr/bin/env python3
"""Generate a logging proxy for a Ubisoft SDK loader DLL (x86_64).

    gen.py <real-loader.dll> <out-dir>

Writes proxy.c and proxy.def. Every export becomes a naked trampoline that saves the
argument registers, logs the call (name + rcx/rdx/r8/r9) and tail-jumps to the real
export in "<name>_real.dll", so it works without knowing any signatures.
"""
import os
import re
import subprocess
import sys

real, out = sys.argv[1], sys.argv[2]
dump = subprocess.run(["winedump", "-j", "export", real], capture_output=True, text=True).stdout
names = [m.group(1) for m in re.finditer(r"^\s+[0-9A-F]+\s+\d+\s+(\S+)", dump, re.M)]
base = os.path.splitext(os.path.basename(real))[0]

c = [f'''// Generated by gen.py from {base}.dll ({len(names)} exports). Do not edit.
#include <windows.h>
#include <stdio.h>
#include <stdint.h>

static const char *NAMES[] = {{ {", ".join(f'"{n}"' for n in names)} }};
void *REAL[{len(names)}];
static FILE *LOG;
static volatile LONG QUIET[{len(names)}];

/* Called from each trampoline with regs = {{r9, r8, rdx, rcx}} as pushed. */
void __cdecl proxy_log(int idx, uint64_t *regs) {{
    if (!LOG) return;
    const char *n = NAMES[idx];
    /* Per-frame calls: log the first few, then stay quiet. */
    if (!strcmp(n, "UPLAY_Update") || !strcmp(n, "UPLAY_GetNextEvent") || !strcmp(n, "UPLAY_PeekNextEvent") ||
        !strcmp(n, "UPLAY_HasOverlappedOperationCompleted") || !strcmp(n, "UPLAY_GetOverlappedOperationResult")) {{
        if (InterlockedIncrement(&QUIET[idx]) > 3) return;
    }}
    SYSTEMTIME t; GetLocalTime(&t);
    fprintf(LOG, "%02d:%02d:%02d.%03d tid=%lu %s(rcx=%llx rdx=%llx r8=%llx r9=%llx)\\n", t.wHour, t.wMinute, t.wSecond,
            t.wMilliseconds, GetCurrentThreadId(), n, regs[3], regs[2], regs[1], regs[0]);
    fflush(LOG);
}}

BOOL WINAPI DllMain(HINSTANCE inst, DWORD reason, LPVOID r) {{
    (void)r;
    if (reason != DLL_PROCESS_ATTACH) return TRUE;
    char path[MAX_PATH]; GetModuleFileNameA(inst, path, MAX_PATH);
    char *slash = strrchr(path, '\\\\'); if (slash) slash[1] = 0;
    strcat(path, "{base}_real.dll");
    HMODULE real = LoadLibraryA(path);
    if (!real) return FALSE;
    for (int i = 0; i < {len(names)}; i++) REAL[i] = (void *)GetProcAddress(real, NAMES[i]);
    const char *log = getenv("UBI_SDK_LOG");
    LOG = fopen(log ? log : "Z:\\\\out\\\\sdk-calls.log", "a");
    if (LOG) fprintf(LOG, "--- %s loaded\\n", path);
    return TRUE;
}}
''']
for i, n in enumerate(names):
    c.append(f'''__attribute__((naked)) void {n}(void) {{
    __asm__ volatile(
        "push %rcx\\n push %rdx\\n push %r8\\n push %r9\\n"
        "sub $0x68, %rsp\\n"
        "movdqu %xmm0, 0x20(%rsp)\\n movdqu %xmm1, 0x30(%rsp)\\n movdqu %xmm2, 0x40(%rsp)\\n movdqu %xmm3, 0x50(%rsp)\\n"
        "mov ${i}, %ecx\\n lea 0x68(%rsp), %rdx\\n call proxy_log\\n"
        "movdqu 0x20(%rsp), %xmm0\\n movdqu 0x30(%rsp), %xmm1\\n movdqu 0x40(%rsp), %xmm2\\n movdqu 0x50(%rsp), %xmm3\\n"
        "add $0x68, %rsp\\n"
        "pop %r9\\n pop %r8\\n pop %rdx\\n pop %rcx\\n"
        "jmp *REAL+{8 * i}(%rip)\\n");
}}''')
open(os.path.join(out, "proxy.c"), "w").write("\n".join(c) + "\n")
open(os.path.join(out, "proxy.def"), "w").write(f"LIBRARY {base}\nEXPORTS\n" + "\n".join(f"    {n}" for n in names) + "\n")
print(f"{len(names)} exports")
