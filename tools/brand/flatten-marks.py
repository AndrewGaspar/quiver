#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.11"
# dependencies = ["shapely>=2"]
# ///
"""Write Quiver's mark ("Parallax") as flat SVG: filled paths only.

The mark was drawn with strokes, a dash pattern for the ring's gap and a <mask> for the
overlap of the cyan/red pair, and the app icon nested an <svg> to place it. Qt's renderer
(QtSvg, SVG Tiny 1.2: the Omarchy launcher, dock and notifications) drops a nested <svg>, older
Qt drops masks, and renderers disagree on where a circle's dash pattern starts. So every
shipped copy is generated here as plain filled outlines: the left copy, the right copy, and
their overlap computed as a shape, painted in that order. No masks, clips, dashes, CSS or
nested documents; only <g transform> for placement.

    tools/brand/flatten-marks.py            # rewrite the SVGs in place
    tools/render-icons.sh                   # then the PNG renders of the app icon

The geometry is the original artwork's, on its 100-unit canvas: before the quarter turn
(rotate(90 50 52)) the ring is a circle at (50,52), radius 30, 10 wide, drawn clockwise from
3 o'clock for 150 units of its 188.5 (butt ends); the tail a round-capped line (44,58)-(72,30);
the head a triangle. The pair sits 3.5 units either side.
"""

import math
import pathlib

from shapely import affinity
from shapely.geometry import LineString, MultiPolygon, Polygon
from shapely.ops import unary_union

ROOT = pathlib.Path(__file__).resolve().parents[2]

# Sub-pixel even on a 512 px icon (one unit is about 5 px there).
TOLERANCE = 0.01


def ring(width):
    r_in, r_out = 30 - width / 2, 30 + width / 2
    sweep = 150 / 30  # radians of dash
    n = 1440
    outer = [(50 + r_out * math.cos(sweep * i / n), 52 + r_out * math.sin(sweep * i / n)) for i in range(n + 1)]
    inner = [(50 + r_in * math.cos(sweep * i / n), 52 + r_in * math.sin(sweep * i / n)) for i in range(n, -1, -1)]
    return Polygon(outer + inner)


def mark(width, head):
    tail = LineString([(44, 58), (72, 30)]).buffer(width / 2, quad_segs=64)
    shape = unary_union([ring(width), tail, Polygon(head)])
    return affinity.rotate(shape, 90, origin=(50, 52))


def polys(geom):
    if isinstance(geom, Polygon):
        return [geom] if not geom.is_empty else []
    if isinstance(geom, MultiPolygon):
        return list(geom.geoms)
    return [g for g in getattr(geom, "geoms", []) if isinstance(g, Polygon) and not g.is_empty]


def fmt(v):
    s = f"{v:.2f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def ring_d(coords):
    pts = list(coords)[:-1]
    out = [f"M{fmt(pts[0][0])} {fmt(pts[0][1])}"]
    out += [f"L{fmt(x)} {fmt(y)}" for x, y in pts[1:]]
    return "".join(out) + "Z"


def path_d(geom):
    geom = geom.simplify(TOLERANCE, preserve_topology=True)
    parts = []
    for p in polys(geom):
        parts.append(ring_d(p.exterior.coords))
        parts += [ring_d(i.coords) for i in p.interiors]
    return "".join(parts)


def pair(width=10, head=((88, 14), (64, 19), (83, 38)), shift=3.5):
    m = mark(width, head)
    left = affinity.translate(m, -shift, 0)
    right = affinity.translate(m, shift, 0)
    return path_d(left), path_d(right), path_d(left.intersection(right))


def stereo(left, right, overlap, colours):
    c_left, c_right, c_overlap = colours
    return (
        f'<path fill="{c_left}" fill-rule="evenodd" d="{left}"/>\n'
        f'<path fill="{c_right}" fill-rule="evenodd" d="{right}"/>\n'
        f'<path fill="{c_overlap}" fill-rule="evenodd" d="{overlap}"/>\n'
    )


DARK = ("#3FC8E4", "#FF6A55", "#F4F1EC")
LIGHT = ("#1FA9CB", "#F0503C", "#1C2226")
FLAT = "Flat SVG (filled paths, no masks or nested <svg>), generated by tools/brand/flatten-marks.py."


def main():
    left, right, overlap = pair()
    marks = {
        "mark-dark.svg": (DARK, "on dark grounds"),
        "mark-light.svg": (LIGHT, "on light grounds"),
    }
    for name, (colours, where) in marks.items():
        svg = (
            '<svg xmlns="http://www.w3.org/2000/svg" width="100" height="100" viewBox="0 0 100 100">\n'
            f'<!-- Quiver\'s mark ("Parallax"), {where}: a Q whose tail is an arrow leaving the ring, '
            f"drawn as a left/right pair with their overlap in the third colour. {FLAT} -->\n"
            + stereo(left, right, overlap, colours)
            + "</svg>\n"
        )
        for d in ("docs/brand", "crates/quiver-ui/assets/brand"):
            (ROOT / d / name).write_text(svg)

    mono = path_d(mark(13, ((90, 12), (62, 17), (85, 40))))
    (ROOT / "crates/quiver-ui/assets/brand/mark-mono.svg").write_text(
        '<svg xmlns="http://www.w3.org/2000/svg" width="100" height="100" viewBox="0 0 100 100">\n'
        f"<!-- One-ink mark for tinting (GPUI svg() uses it as a mask). {FLAT} -->\n"
        f'<path fill="#000" fill-rule="evenodd" d="{mono}"/>\n'
        "</svg>\n"
    )

    # The app icon: the mark on the night ground, its 100 units in a 96-unit box at (16,16).
    (ROOT / "contrib/quiver.svg").write_text(
        '<svg xmlns="http://www.w3.org/2000/svg" width="128" height="128" viewBox="0 0 128 128">\n'
        f"<!-- Quiver's app icon: the Parallax mark on the night ground. {FLAT}\n"
        "     PNG renders for raster-only consumers: tools/render-icons.sh. -->\n"
        '<rect x="4" y="4" width="120" height="120" rx="28" ry="28" fill="#15171D"/>\n'
        '<rect x="4.5" y="4.5" width="119" height="119" rx="27.5" ry="27.5" fill="none" stroke="#2A2D35"/>\n'
        '<g transform="translate(16 16) scale(0.96)">\n'
        + stereo(left, right, overlap, DARK)
        + "</g>\n</svg>\n"
    )


if __name__ == "__main__":
    main()
